"""Render the Day 2 sandbox SOPs from sops/*.md into one page fragment, day2-sops.html, for build.py.

Run with: uv run --with markdown python make_sops.py
"""

import pathlib
import re

import markdown

HERE = pathlib.Path(__file__).parent
SOPS = ["FM-SOP-03", "FM-SOP-07", "FM-SOP-15", "ADM-SOP-02"]
"""The four SOPs participants load as agent knowledge on Day 2, in page order."""


def section(sop_id: str) -> str:
    """Return one SOP as a page section; its own ## headings drop one level to sit under the SOP title."""
    text = (HERE / "sops" / f"{sop_id}.md").read_text()
    front, body = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S).groups()
    title = re.search(r'title:\s*"(.*)"', front).group(1)
    html = markdown.markdown(body, extensions=["tables"])
    html = re.sub(r"<(/?)h2>", r"<\1h3>", html).replace("<h3>", '<h3 class="sec">')
    html = html.replace("<table>", '<div class="scroll"><table>').replace(
        "</table>", "</table></div>"
    )
    return (
        f'  <section class="part" id="{sop_id.lower()}">\n'
        f'    <div class="part-head"><p class="kicker">Sandbox SOP</p><h2>{title}</h2></div>\n'
        f'    <div class="prose sop">\n{html}\n    </div>\n  </section>'
    )


def main() -> None:
    """Write build/day2-sops.html."""
    toc = "\n".join(
        f'      <li><a href="#{s.lower()}"><span class="t">{s}</span><span>'
        f"{re.search(r'· (.*)\"', (HERE / 'sops' / f'{s}.md').read_text()).group(1)}</span></a></li>"
        for s in SOPS
    )
    body = "\n\n".join(section(s) for s in SOPS)
    page = f"""<title>TIYA AI Day 2 Sandbox SOPs</title>
<!-- Generated by make_sops.py from sops/*.md. Edit the Markdown, not this file. -->
<style>
.sop {{ max-width: none; }}
.sop table {{ font-size: 15px; }}
.sop thead th:empty {{ display: none; }}
</style>
<header class="mast">
  <div class="wrap">
    <div class="mast-top"><a class="home" href="participants.html" aria-label="Participant materials">{{{{LOGO}}}}</a><span class="mast-tag"><a class="kit-link" href="participants.html">← Participant materials</a> · Day 2 · Sandbox SOPs</span></div>
    <div style="display:grid;gap:12px">
      <h1>Applied AI at TIYA Services: Day 2 Sandbox SOPs</h1>
      <p class="mast-sub">The four standard operating procedures the Day 2 agents use as knowledge, on one page. Point an agent at this page's URL, or link to one SOP with its section link. Every document here is fictional, for training only.</p>
    </div>
  </div>
  <div class="gold-rule"></div>
</header>

<main class="wrap">
  <nav class="toc" aria-label="Contents">
    <h4 class="sub">Contents</h4>
    <ol>
{toc}
    </ol>
  </nav>

{body}
</main>

<footer class="foot">
  <div class="wrap">{{{{LOGO}}}}<p>Applied AI at TIYA Services · Day 2 sandbox SOPs · Fictional, for training only.</p></div>
</footer>
"""
    _ = (HERE / "day2-sops.html").write_text(page)
    print(f"day2-sops.html  {len(SOPS)} SOPs")


if __name__ == "__main__":
    main()
