def main() -> None:
    """Write every generated fragment."""
    _ = (HERE / "index.html").write_text(index())
    _ = (HERE / "participants.html").write_text(participants_chooser())
    for key in DAYS:
        _ = (HERE / f"participants-{key}.html").write_text(participants_day(key))
    print(
        "index.html  participants.html  "
        + "  ".join(f"participants-{k}.html" for k in DAYS)
    )


if __name__ == "__main__":
    main()
